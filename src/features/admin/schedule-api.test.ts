import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { login, logout } from '@/features/auth/api'
import { koreaToday } from '@/shared/i18n/format'
import {
  createAdminSchedule,
  fetchAdminSchedules,
  generateTaxSchedules,
  updateAdminSchedule,
  type AdminScheduleRequest,
} from './schedule-api'

// Contract tests against the MSW mock (not the real BE).
const origin = 'http://localhost'
const admin = { email: 'admin@example.com', password: 'admin1234' }
const member = { email: 'taken@example.com', password: 'abcd1234' }
const year = Number(koreaToday().slice(0, 4))

beforeEach(() => {
  const interceptedFetch = globalThis.fetch
  vi.stubGlobal('document', { cookie: 'XSRF-TOKEN=token' })
  vi.stubGlobal(
    'fetch',
    vi.fn((input: string | URL | Request, init?: RequestInit) =>
      interceptedFetch(
        typeof input === 'string' ? new URL(input, origin) : input,
        init,
      ),
    ),
  )
})
afterEach(() => vi.unstubAllGlobals())

const extension: AdminScheduleRequest = {
  kind: 'TAX_CAR',
  guideCode: 'tax-car',
  startsOn: `${year}-06-16`,
  endsOn: `${year}-07-10`,
  targetDescription: '  기한 연장  ',
  sourceUrl: 'https://www.wetax.go.kr',
  active: true,
}

describe('CAL-01~03·NTF-01 admin schedules', () => {
  it('is for admins only', async () => {
    await expect(fetchAdminSchedules(year)).rejects.toMatchObject({
      status: 401,
    })
    await login(member)
    await expect(fetchAdminSchedules(year)).rejects.toMatchObject({
      status: 403,
      code: 'FORBIDDEN',
    })
    await expect(createAdminSchedule(extension)).rejects.toMatchObject({
      status: 403,
    })
    await expect(updateAdminSchedule(1, extension)).rejects.toMatchObject({
      status: 403,
    })
    await expect(generateTaxSchedules(year)).rejects.toMatchObject({
      status: 403,
    })
    await logout()
  })

  it('lists the year by start date, inactive and generated ones included', async () => {
    await login(admin)
    const rows = await fetchAdminSchedules(year)
    const starts = rows.map((row) => row.startsOn)
    expect(starts).toEqual([...starts].sort())
    expect(rows.every((row) => row.startsOn.startsWith(`${year}-`))).toBe(true)
    expect(rows.some((row) => !row.active)).toBe(true)
    expect(rows.find((row) => row.kind === 'TAX_CAR')).toMatchObject({
      autoGenerated: true,
      createdBy: null,
      guideCode: 'tax-car',
    })

    // A kind matches its own kind or a linked tax rule of that kind.
    const cars = await fetchAdminSchedules(year, 'TAX_CAR')
    expect(new Set(cars.map((row) => row.kind))).toEqual(
      new Set(['TAX_CAR', 'TAX_CAR_ANNUAL']),
    )
    await expect(fetchAdminSchedules(year + 50)).resolves.toEqual([])
    await expect(fetchAdminSchedules(1999)).rejects.toMatchObject({
      status: 400,
      code: 'INVALID_INPUT',
    })
    await logout()
  })

  it('creates (201) and overwrites every value on update', async () => {
    await login(admin)
    const created = await createAdminSchedule(extension)
    expect(created).toMatchObject({
      kind: 'TAX_CAR',
      guideCode: 'tax-car',
      targetDescription: '기한 연장',
      active: true,
      autoGenerated: false,
      createdBy: 2,
      updatedBy: null,
    })

    const updated = await updateAdminSchedule(created.scheduleId, {
      ...extension,
      guideCode: null,
      endsOn: null,
      targetDescription: '',
      sourceUrl: null,
      active: false,
    })
    expect(updated).toMatchObject({
      scheduleId: created.scheduleId,
      guideCode: null,
      endsOn: null,
      targetDescription: null,
      sourceUrl: null,
      active: false,
      updatedBy: 2,
    })
    const rows = await fetchAdminSchedules(year)
    expect(rows.find((row) => row.scheduleId === created.scheduleId)).toEqual(
      updated,
    )
    await logout()
  })

  it('rejects bad input like the BE', async () => {
    await login(admin)
    for (const body of [
      { ...extension, kind: 'tax_car' },
      { ...extension, kind: 'A'.repeat(31) },
      { ...extension, endsOn: `${year}-06-01` },
      { ...extension, sourceUrl: 'www.wetax.go.kr' },
    ])
      await expect(createAdminSchedule(body)).rejects.toMatchObject({
        status: 400,
        code: 'INVALID_INPUT',
      })
    await expect(
      createAdminSchedule({ ...extension, guideCode: 'no-such-item' }),
    ).rejects.toMatchObject({ status: 404, code: 'GUIDE_NOT_FOUND' })
    await expect(updateAdminSchedule(99999, extension)).rejects.toMatchObject({
      status: 404,
      code: 'SCHEDULE_NOT_FOUND',
    })
    await logout()
  })

  it('generates only the missing regular tax rounds', async () => {
    await login(admin)
    // This year's rounds are seeded (one corrected, so it is kept as it is).
    await expect(generateTaxSchedules(year)).resolves.toEqual({
      year,
      created: [],
      officialHolidays: true,
    })

    const next = await generateTaxSchedules(year + 1)
    expect(next.officialHolidays).toBe(false)
    expect(next.created.map((row) => row.startsOn)).toEqual(
      [6, 7, 8, 9, 12].map(
        (month) => `${year + 1}-${String(month).padStart(2, '0')}-16`,
      ),
    )
    for (const row of next.created) {
      expect(row).toMatchObject({ autoGenerated: true, active: true })
      // The month's last day or the next working day after it.
      const end = new Date(`${row.endsOn}T00:00:00Z`)
      expect([0, 6]).not.toContain(end.getUTCDay())
      expect(row.endsOn! >= row.startsOn).toBe(true)
    }
    const again = await generateTaxSchedules(year + 1)
    expect(again.created).toEqual([])
    await logout()
  })

  it('does not remake a round that was turned off', async () => {
    await login(admin)
    const [round] = (await generateTaxSchedules(year + 2)).created
    await updateAdminSchedule(round.scheduleId, {
      kind: round.kind,
      guideCode: round.guideCode,
      startsOn: round.startsOn,
      endsOn: round.endsOn,
      targetDescription: null,
      sourceUrl: round.sourceUrl,
      active: false,
    })
    await expect(generateTaxSchedules(year + 2)).resolves.toMatchObject({
      created: [],
    })
    await logout()
  })
})
