import { apiRequest } from '@/shared/api/client'

/** Tax kinds the BE generates every year (BE `TaxKind`). Other kinds are free text. */
export const taxScheduleKinds = [
  'TAX_CAR',
  'TAX_PROPERTY',
  'TAX_RESIDENT',
] as const

/** Same rule as the BE: a kind containing TAX is a tax (detail and D-7·D-1 alerts). */
export const isTaxKind = (kind: string) => kind.toUpperCase().includes('TAX')

/** CAL-01~03 `AdminScheduleResponse`: a common calendar schedule. */
export interface AdminSchedule {
  scheduleId: number
  /** TAX_CAR, TAX_PROPERTY, TAX_RESIDENT or any upper-case kind. */
  kind: string
  /** Linked item; title, text and contact come from it. */
  guideCode: string | null
  startsOn: string
  /** null → one day (startsOn). */
  endsOn: string | null
  /** Shown as is in every language. */
  targetDescription: string | null
  sourceUrl: string | null
  /** false → hidden from calendars and alerts (there is no delete). */
  active: boolean
  /** Made by the server (no admin created it). */
  autoGenerated: boolean
  createdBy: number | null
  updatedBy: number | null
  updatedAt: string
}

/** `AdminScheduleRequest`: PUT overwrites every value. */
export interface AdminScheduleRequest {
  kind: string
  guideCode: string | null
  startsOn: string
  endsOn: string | null
  targetDescription: string | null
  sourceUrl: string | null
  active: boolean
}

/** `POST /api/admin/schedules/taxes/generate` result. */
export interface TaxScheduleGenerateResponse {
  year: number
  /** Rounds made now; rounds that already existed are left out. */
  created: AdminSchedule[]
  /**
   * false → deadlines were moved for weekends and fixed solar holidays only;
   * check the ones on Seollal, Chuseok, substitute or temporary holidays.
   */
  officialHolidays: boolean
}

/** BE accepts 2000~2100. */
export const scheduleYearRange = { min: 2000, max: 2100 } as const

export const adminScheduleKeys = {
  all: ['admin', 'schedules'] as const,
  year: (year: number) => [...adminScheduleKeys.all, year] as const,
  list: (year: number, kind: string) =>
    [...adminScheduleKeys.year(year), kind] as const,
}

/** Schedules starting in the year, inactive ones too, by start date. */
export function fetchAdminSchedules(year: number, kind = '') {
  const search = new URLSearchParams({ year: String(year) })
  if (kind) search.set('kind', kind)
  return apiRequest<AdminSchedule[]>(
    `/api/admin/schedules?${search.toString()}`,
  )
}

/** 201. 404 GUIDE_NOT_FOUND for an unknown item, 400 INVALID_INPUT otherwise. */
export function createAdminSchedule(body: AdminScheduleRequest) {
  return apiRequest<AdminSchedule>('/api/admin/schedules', {
    method: 'POST',
    body,
  })
}

/** Overwrites every value. 404 SCHEDULE_NOT_FOUND or GUIDE_NOT_FOUND. */
export function updateAdminSchedule(
  scheduleId: number,
  body: AdminScheduleRequest,
) {
  return apiRequest<AdminSchedule>(`/api/admin/schedules/${scheduleId}`, {
    method: 'PUT',
    body,
  })
}

/** Makes the year's missing regular tax rounds; existing ones stay as they are. */
export function generateTaxSchedules(year: number) {
  return apiRequest<TaxScheduleGenerateResponse>(
    `/api/admin/schedules/taxes/generate?year=${year}`,
    { method: 'POST' },
  )
}
