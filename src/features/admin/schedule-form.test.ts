import { describe, expect, it } from 'vitest'
import type { AdminSchedule } from './schedule-api'
import { isTaxKind } from './schedule-api'
import {
  parseScheduleYear,
  scheduleLink,
  schedulePeriod,
  scheduleSchema,
  toScheduleForm,
  toScheduleRequest,
  weekday,
  type ScheduleForm,
} from './schedule-form'

const saved: AdminSchedule = {
  scheduleId: 10,
  kind: 'TAX_CAR',
  guideCode: 'tax-car',
  startsOn: '2027-06-16',
  endsOn: '2027-06-30',
  targetDescription: null,
  sourceUrl: 'https://www.wetax.go.kr',
  active: true,
  autoGenerated: true,
  createdBy: null,
  updatedBy: null,
  updatedAt: '2027-01-01T04:30:00+09:00',
}

/** First message per field, as the form shows it. */
const issues = (form: ScheduleForm) => {
  const result = scheduleSchema.safeParse(form)
  const first: Record<string, string> = {}
  if (!result.success)
    for (const issue of result.error.issues)
      first[String(issue.path[0])] ??= issue.message
  return first
}

describe('schedule form', () => {
  it('round-trips a saved schedule and sends every value', () => {
    const form = toScheduleForm(saved)
    expect(form).toEqual({
      kind: 'TAX_CAR',
      guideCode: 'tax-car',
      startsOn: '2027-06-16',
      endsOn: '2027-06-30',
      targetDescription: '',
      sourceUrl: 'https://www.wetax.go.kr',
      active: true,
    })
    expect(toScheduleRequest(scheduleSchema.parse(form))).toEqual({
      kind: 'TAX_CAR',
      guideCode: 'tax-car',
      startsOn: '2027-06-16',
      endsOn: '2027-06-30',
      targetDescription: null,
      sourceUrl: 'https://www.wetax.go.kr',
      active: true,
    })
  })

  it('clears empty values and keeps active off', () => {
    const form = {
      ...toScheduleForm(saved),
      guideCode: '',
      endsOn: '',
      targetDescription: '  ',
      sourceUrl: ' ',
      active: false,
    }
    expect(toScheduleRequest(scheduleSchema.parse(form))).toMatchObject({
      guideCode: null,
      endsOn: null,
      targetDescription: null,
      sourceUrl: null,
      active: false,
    })
  })

  it('starts empty and active for a new schedule', () => {
    expect(toScheduleForm(null)).toMatchObject({
      kind: '',
      startsOn: '',
      active: true,
    })
  })

  it('checks the rules the BE checks', () => {
    const base = toScheduleForm(saved)
    expect(issues(base)).toEqual({})
    expect(issues({ ...base, kind: '' })).toEqual({
      kind: 'admin.schedules.kindRequired',
    })
    expect(issues({ ...base, kind: 'tax_car' })).toEqual({
      kind: 'admin.schedules.kindFormat',
    })
    expect(issues({ ...base, kind: '1TAX' })).toEqual({
      kind: 'admin.schedules.kindFormat',
    })
    expect(issues({ ...base, kind: 'A'.repeat(31) }).kind).toBe('admin.tooLong')
    expect(issues({ ...base, startsOn: '' })).toEqual({
      startsOn: 'admin.schedules.startsOnRequired',
    })
    expect(issues({ ...base, endsOn: '2027-06-15' })).toEqual({
      endsOn: 'admin.schedules.dateOrder',
    })
    expect(issues({ ...base, endsOn: '2027-06-16' })).toEqual({})
    expect(issues({ ...base, sourceUrl: 'www.wetax.go.kr' })).toEqual({
      sourceUrl: 'admin.documents.urlInvalid',
    })
    expect(issues({ ...base, targetDescription: 'a'.repeat(1001) })).toEqual({
      targetDescription: 'admin.tooLong',
    })
  })
})

describe('schedule display', () => {
  it('shows weekdays so a deadline on a day off stands out', () => {
    expect(weekday('2027-07-31')).toBe('토')
    expect(weekday('not-a-date')).toBe('')
    expect(schedulePeriod('2027-07-16', '2027-08-02')).toBe(
      '2027-07-16 (금) ~ 2027-08-02 (월)',
    )
    expect(schedulePeriod('2027-01-16', null)).toBe('2027-01-16 (토)')
    expect(schedulePeriod('2027-01-16', '2027-01-16')).toBe('2027-01-16 (토)')
  })

  it('links to the start year and reads only a valid year', () => {
    expect(scheduleLink(saved)).toBe('/admin/schedules/10?year=2027')
    expect(parseScheduleYear('2027')).toBe(2027)
    for (const value of [null, '', '27', '1999', '2101', '2027a'])
      expect(parseScheduleYear(value)).toBeUndefined()
  })

  it('treats any kind with TAX as a tax, like the BE', () => {
    expect(isTaxKind('TAX_CAR_ANNUAL')).toBe(true)
    expect(isTaxKind('LOCAL_TAXES')).toBe(true)
    expect(isTaxKind('HOLIDAY')).toBe(false)
  })
})
