import type { TFunction } from 'i18next'
import { z } from 'zod'
import { formatDateTime } from '@/shared/i18n/format'
import {
  scheduleYearRange,
  taxScheduleKinds,
  type AdminSchedule,
  type AdminScheduleRequest,
} from './schedule-api'

/** Same limits as the BE AdminScheduleRequest. */
export const scheduleMaxLength = {
  kind: 30,
  targetDescription: 1000,
  sourceUrl: 2000,
} as const
const kindPattern = /^[A-Z][A-Z0-9_]*$/
const urlPattern = /^https?:\/\/\S+$/

/** All inputs are strings except `active`; "" = empty. */
export const scheduleSchema = z
  .object({
    kind: z
      .string()
      .trim()
      .min(1, 'admin.schedules.kindRequired')
      .max(scheduleMaxLength.kind, 'admin.tooLong')
      .regex(kindPattern, 'admin.schedules.kindFormat'),
    /** "" = no linked item. */
    guideCode: z.string(),
    /** YYYY-MM-DD */
    startsOn: z.string().min(1, 'admin.schedules.startsOnRequired'),
    endsOn: z.string(),
    targetDescription: z
      .string()
      .trim()
      .max(scheduleMaxLength.targetDescription, 'admin.tooLong'),
    sourceUrl: z
      .string()
      .trim()
      .max(scheduleMaxLength.sourceUrl, 'admin.tooLong')
      .refine(
        (value) => !value || urlPattern.test(value),
        'admin.documents.urlInvalid',
      ),
    active: z.boolean(),
  })
  .superRefine((form, ctx) => {
    // The BE checks it too (400 INVALID_INPUT).
    if (form.startsOn && form.endsOn && form.endsOn < form.startsOn)
      ctx.addIssue({
        code: 'custom',
        path: ['endsOn'],
        message: 'admin.schedules.dateOrder',
      })
  })
export type ScheduleForm = z.input<typeof scheduleSchema>
export type ParsedScheduleForm = z.output<typeof scheduleSchema>

export function toScheduleForm(saved?: AdminSchedule | null): ScheduleForm {
  return {
    kind: saved?.kind ?? '',
    guideCode: saved?.guideCode ?? '',
    startsOn: saved?.startsOn ?? '',
    endsOn: saved?.endsOn ?? '',
    targetDescription: saved?.targetDescription ?? '',
    sourceUrl: saved?.sourceUrl ?? '',
    active: saved?.active ?? true,
  }
}

const orNull = (value: string) => value || null

/** Create and update send every value (PUT overwrites, "" → null clears). */
export function toScheduleRequest(
  form: ParsedScheduleForm,
): AdminScheduleRequest {
  return {
    kind: form.kind,
    guideCode: orNull(form.guideCode),
    startsOn: form.startsOn,
    endsOn: orNull(form.endsOn),
    targetDescription: orNull(form.targetDescription),
    sourceUrl: orNull(form.sourceUrl),
    active: form.active,
  }
}

/** Year of a YYYY-MM-DD date: the list (and the edit link) is by start year. */
export const scheduleYear = (startsOn: string) => Number(startsOn.slice(0, 4))

/** Korean weekday of a YYYY-MM-DD date ("월"), '' when invalid. */
export function weekday(date: string) {
  const time = Date.parse(`${date}T00:00:00Z`)
  if (Number.isNaN(time)) return ''
  return new Intl.DateTimeFormat('ko-KR', {
    weekday: 'short',
    timeZone: 'UTC',
  }).format(time)
}

/**
 * "2027-06-16 (수) ~ 2027-06-30 (수)". A missing end means one day, as on the
 * member calendar. Weekdays help check a deadline that falls on a day off.
 */
export function schedulePeriod(startsOn: string, endsOn: string | null) {
  const day = (date: string) => `${date} (${weekday(date)})`
  return !endsOn || endsOn === startsOn
    ? day(startsOn)
    : `${day(startsOn)} ~ ${day(endsOn)}`
}

/** Year in the address (`?year=`), within the BE range; otherwise undefined. */
export function parseScheduleYear(value: string | null) {
  if (!value || !/^\d{4}$/.test(value)) return undefined
  const year = Number(value)
  return year >= scheduleYearRange.min && year <= scheduleYearRange.max
    ? year
    : undefined
}

/** "자동차세 (TAX_CAR)" for the regular tax kinds, the code otherwise. */
export function kindLabel(t: TFunction, kind: string) {
  return (taxScheduleKinds as readonly string[]).includes(kind)
    ? `${t(`admin.schedules.kinds.${kind}`)} (${kind})`
    : kind
}

/** Edit link; the edit screen finds the schedule in its start year's list. */
export const scheduleLink = (schedule: AdminSchedule) =>
  `/admin/schedules/${schedule.scheduleId}?year=${scheduleYear(schedule.startsOn)}`

/** "#7 · 관리자 #2 등록 · 관리자 #2 고침 · 마지막 수정 …" */
export function scheduleMeta(
  t: TFunction,
  schedule: AdminSchedule,
  language: string,
) {
  return [
    `#${schedule.scheduleId}`,
    schedule.autoGenerated
      ? t('admin.schedules.createdByAuto')
      : schedule.createdBy !== null &&
        t('admin.schedules.createdBy', { id: schedule.createdBy }),
    schedule.updatedBy !== null &&
      t('admin.schedules.updatedBy', { id: schedule.updatedBy }),
    t('admin.updatedAt', {
      date: formatDateTime(schedule.updatedAt, language),
    }),
  ]
    .filter(Boolean)
    .join(' · ')
}
