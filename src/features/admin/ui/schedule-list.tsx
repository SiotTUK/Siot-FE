import { useTranslation } from 'react-i18next'
import { Link, useSearchParams } from 'react-router-dom'
import { currentLanguage } from '@/shared/i18n'
import { errorMessage } from '@/shared/i18n/error-message'
import { koreaToday } from '@/shared/i18n/format'
import { Button, ButtonLink } from '@/shared/ui/button'
import { SelectField } from '@/shared/ui/field'
import {
  Card,
  FormError,
  Muted,
  Notice,
  Section,
  Stack,
  Tag,
  Toolbar,
} from '@/shared/ui/page'
import { QueryState } from '@/shared/ui/query-state'
import {
  isTaxKind,
  taxScheduleKinds,
  type AdminSchedule,
} from '../schedule-api'
import {
  kindLabel,
  parseScheduleYear,
  scheduleLink,
  scheduleMeta,
  schedulePeriod,
} from '../schedule-form'
import {
  useAdminSchedules,
  useGenerateTaxSchedules,
  useGuideTitles,
} from '../use-admin-schedules'
import styles from './admin.module.css'

/**
 * CAL-01~03·NTF-01: common calendar schedules of a year (inactive too), with
 * the regular tax rounds' generation. Year and kind stay in the address so
 * the edit screen's back link returns to the same list.
 */
export function ScheduleList() {
  const { t } = useTranslation()
  const [params, setParams] = useSearchParams()
  const thisYear = Number(koreaToday().slice(0, 4))
  const year = parseScheduleYear(params.get('year')) ?? thisYear
  const kind = params.get('kind') ?? ''
  const schedules = useAdminSchedules(year, kind)
  // Every kind of the year, for the filter options (same cache as the edit screen).
  const yearSchedules = useAdminSchedules(year)
  const { titles } = useGuideTitles()

  const years = Array.from({ length: 6 }, (_, index) => thisYear - 3 + index)
  if (!years.includes(year)) years.push(year)
  years.sort((a, b) => a - b)
  const kinds = [
    ...new Set([
      ...taxScheduleKinds,
      ...(yearSchedules.data?.map((schedule) => schedule.kind) ?? []),
      ...(kind ? [kind] : []),
    ]),
  ]
  const change = (key: 'year' | 'kind', value: string) =>
    setParams(
      (current) => {
        const next = new URLSearchParams(current)
        if (value) next.set(key, value)
        else next.delete(key)
        return next
      },
      { replace: true },
    )

  return (
    <>
      <ButtonLink to={`/admin/schedules/new?year=${year}`}>
        {t('admin.schedules.create')}
      </ButtonLink>
      <GeneratePanel key={year} year={year} />
      <Toolbar>
        <SelectField
          label={t('admin.schedules.year')}
          value={String(year)}
          onChange={(event) => change('year', event.target.value)}
          options={years.map((value) => ({
            value: String(value),
            label: t('admin.schedules.yearOption', { year: value }),
          }))}
        />
        <SelectField
          label={t('admin.schedules.kind')}
          value={kind}
          onChange={(event) => change('kind', event.target.value)}
          options={[
            { value: '', label: t('admin.all') },
            ...kinds.map((value) => ({
              value,
              label: kindLabel(t, value),
            })),
          ]}
        />
      </Toolbar>
      <Muted>{t('admin.schedules.listHelp')}</Muted>
      <QueryState query={schedules}>
        {schedules.data?.length === 0 ? (
          <Muted>{t('admin.schedules.empty')}</Muted>
        ) : (
          <Stack gap={12}>
            {schedules.data?.map((schedule) => (
              <ScheduleRow
                key={schedule.scheduleId}
                schedule={schedule}
                guideTitle={
                  schedule.guideCode
                    ? titles.get(schedule.guideCode)
                    : undefined
                }
              />
            ))}
          </Stack>
        )}
      </QueryState>
    </>
  )
}

/** Status tags: off, made by the server or an admin, tax alerts. */
export function ScheduleTags({ schedule }: { schedule: AdminSchedule }) {
  const { t } = useTranslation()
  return (
    <p className={styles.tags}>
      {!schedule.active && (
        <Tag tone="danger">{t('admin.schedules.inactive')}</Tag>
      )}
      <Tag tone={schedule.autoGenerated ? 'neutral' : 'main'}>
        {t(
          schedule.autoGenerated
            ? 'admin.schedules.autoGenerated'
            : 'admin.schedules.manual',
        )}
      </Tag>
      {isTaxKind(schedule.kind) && (
        <Tag tone="warning">{t('admin.schedules.taxAlert')}</Tag>
      )}
    </p>
  )
}

function ScheduleRow({
  schedule,
  guideTitle,
}: {
  schedule: AdminSchedule
  guideTitle: string | undefined
}) {
  const { t } = useTranslation()
  return (
    <Link className="plain-link" to={scheduleLink(schedule)}>
      <Card>
        {/*
          Members see the linked item's title, or the raw kind without one
          (BE). Item titles not loaded yet → the kind's Korean name.
        */}
        <strong>
          {schedule.guideCode
            ? (guideTitle ?? kindLabel(t, schedule.kind))
            : schedule.kind}
        </strong>
        <Muted>{schedulePeriod(schedule.startsOn, schedule.endsOn)}</Muted>
        <ScheduleTags schedule={schedule} />
        <Muted>
          {t('admin.schedules.kindLine', { kind: schedule.kind })} ·{' '}
          {schedule.guideCode
            ? t('admin.schedules.guideLine', { code: schedule.guideCode })
            : t('admin.schedules.noGuide')}
        </Muted>
        {schedule.targetDescription && (
          <p className={styles.answer}>{schedule.targetDescription}</p>
        )}
        <Muted>{scheduleMeta(t, schedule, currentLanguage())}</Muted>
      </Card>
    </Link>
  )
}

/** POST taxes/generate for the selected year and what it made. */
function GeneratePanel({ year }: { year: number }) {
  const { t } = useTranslation()
  const generate = useGenerateTaxSchedules()
  const result = generate.data
  return (
    <Section title={t('admin.schedules.generateTitle')}>
      <Stack gap={10}>
        <Muted>{t('admin.schedules.generateHelp', { year })}</Muted>
        <Muted>{t('admin.schedules.generateSchedule')}</Muted>
        <Button
          variant="secondary"
          loading={generate.isPending}
          onClick={() => generate.mutate(year)}
        >
          {t('admin.schedules.generate', { year })}
        </Button>
        <FormError
          message={
            generate.isError ? errorMessage(t, generate.error) : undefined
          }
        />
        {result && result.created.length === 0 && (
          <Notice tone="success">
            {t('admin.schedules.generateNone', { year: result.year })}
          </Notice>
        )}
        {result && result.created.length > 0 && (
          <Notice
            tone="success"
            title={t('admin.schedules.generateDone', {
              count: result.created.length,
            })}
          >
            <ul className={styles.runs}>
              {result.created.map((schedule) => (
                <li key={schedule.scheduleId}>
                  <Link className={styles.link} to={scheduleLink(schedule)}>
                    {kindLabel(t, schedule.kind)} ·{' '}
                    {schedulePeriod(schedule.startsOn, schedule.endsOn)}
                  </Link>
                </li>
              ))}
            </ul>
          </Notice>
        )}
        {result && !result.officialHolidays && (
          <Notice
            tone="danger"
            title={t('admin.schedules.checkDeadlinesTitle')}
          >
            {t('admin.schedules.checkDeadlines')}
          </Notice>
        )}
      </Stack>
    </Section>
  )
}
