/** Mock-only copy of the BE `TaxKind.forGuideCode`. */
const taxKindByGuideCode: Record<string, string> = {
  'tax-car': 'TAX_CAR',
  'tax-property': 'TAX_PROPERTY',
  'tax-resident': 'TAX_RESIDENT',
}

/** BE `TaxScheduleGenerator.PERIODS`: 16th to the end of the month. */
const periods = [
  { kind: 'TAX_CAR', guideCode: 'tax-car', month: 6 },
  { kind: 'TAX_PROPERTY', guideCode: 'tax-property', month: 7 },
  { kind: 'TAX_RESIDENT', guideCode: 'tax-resident', month: 8 },
  { kind: 'TAX_PROPERTY', guideCode: 'tax-property', month: 9 },
  { kind: 'TAX_CAR', guideCode: 'tax-car', month: 12 },
] as const

/**
 * Weekends and fixed solar holidays only, like a BE without holiday data
 * (`officialHolidays: false`): Seollal, Chuseok and substitute days are missed.
 */
const fixedHolidays = [
  '01-01',
  '03-01',
  '05-01',
  '05-05',
  '06-06',
  '08-15',
  '10-03',
  '10-09',
  '12-25',
]
const dayMs = 86_400_000
const isoDate = (time: number) => new Date(time).toISOString().slice(0, 10)

/** The month's last day, moved to the next working day (지방세기본법 제24조). */
function deadline(year: number, month: number) {
  let time = Date.UTC(year, month, 0)
  const off = (value: number) =>
    [0, 6].includes(new Date(value).getUTCDay()) ||
    fixedHolidays.includes(isoDate(value).slice(5))
  while (off(time)) time += dayMs
  return isoDate(time)
}

const pad = (month: number) => String(month).padStart(2, '0')
const wetax = 'https://www.wetax.go.kr'

function regular(
  scheduleId: number,
  year: number,
  period: (typeof periods)[number],
  updatedAt: string,
): AdminSchedule {
  return {
    scheduleId,
    kind: period.kind,
    guideCode: period.guideCode,
    startsOn: `${year}-${pad(period.month)}-16`,
    endsOn: deadline(year, period.month),
    targetDescription: null,
    sourceUrl: wetax,
    active: true,
    autoGenerated: true,
    createdBy: null,
    updatedBy: null,
    updatedAt,
  }
}

/** This year's regular rounds (one fixed by an admin), plus admin entries. */
function data(): NonNullable<typeof state.adminSchedules> {
  if (!state.adminSchedules) {
    const year = Number(koreaToday().slice(0, 4))
    const seeded = `${year}-01-01T04:30:00+09:00`
    const schedules = periods.map((period, index) =>
      regular(index + 1, year, period, seeded),
    )
    // An auto-generated round an admin has corrected.
    Object.assign(schedules[3], {
      targetDescription: '토지 · 주택 2기분',
      updatedBy: 2,
      updatedAt: `${year}-09-01T10:00:00+09:00`,
    })
    schedules.push(
      {
        scheduleId: 6,
        kind: 'TAX_CAR_ANNUAL',
        guideCode: 'tax-car',
        startsOn: `${year}-01-16`,
        endsOn: `${year}-01-31`,
        targetDescription: '자동차세 연납 신청 · 납부 기간',
        sourceUrl: wetax,
        active: true,
        autoGenerated: false,
        createdBy: 2,
        updatedBy: null,
        updatedAt: `${year}-01-10T09:00:00+09:00`,
      },
      {
        scheduleId: 7,
        kind: 'TAX_RESIDENT',
        guideCode: null,
        startsOn: `${year}-08-16`,
        endsOn: `${year}-08-31`,
        targetDescription: '잘못 넣은 중복 일정',
        sourceUrl: null,
        active: false,
        autoGenerated: false,
        createdBy: 2,
        updatedBy: 2,
        updatedAt: `${year}-08-02T09:00:00+09:00`,
      },
    )
    state.adminSchedules = { schedules, nextId: 100 }
  }
  return state.adminSchedules
}

const invalid = (message = '요청 값이 올바르지 않습니다.') =>
  error(400, 'INVALID_INPUT', message)
const kindPattern = /^[A-Z][A-Z0-9_]*$/
const urlPattern = /^$|^\s*https?:\/\/\S+\s*$/
const isDate = (value: unknown) =>
  typeof value === 'string' &&
  /^\d{4}-\d{2}-\d{2}$/.test(value) &&
  !Number.isNaN(Date.parse(`${value}T00:00:00Z`))

/** `?year=` within 2000~2100, otherwise undefined. */
function yearOf(request: Request) {
  const value = new URL(request.url).searchParams.get('year') ?? ''
  const year = Number(value)
  return /^\d{4}$/.test(value) && year >= 2000 && year <= 2100
    ? year
    : undefined
}

/** BE bean validation of AdminScheduleRequest (checked before anything else). */
function badInput(input: Record<string, unknown>) {
  const text = (key: string, max: number) =>
    input[key] != null &&
    (typeof input[key] !== 'string' || (input[key] as string).length > max)
  const { kind, sourceUrl } = input
  if (typeof kind !== 'string' || !kind.trim() || kind.length > 30) return true
  if (!kindPattern.test(kind)) return true
  if (text('guideCode', 50) || text('targetDescription', 1000)) return true
  if (text('sourceUrl', 2000)) return true
  if (typeof sourceUrl === 'string' && !urlPattern.test(sourceUrl)) return true
  if (!isDate(input.startsOn)) return true
  if (input.endsOn != null && !isDate(input.endsOn)) return true
  return input.active != null && typeof input.active !== 'boolean'
}

const blankToNull = (value: unknown) =>
  typeof value === 'string' && value.trim() ? value.trim() : null

/** Values after validation; undefined guideCode = not found (404). */
function values(input: Record<string, unknown>) {
  const code = blankToNull(input.guideCode)
  return {
    kind: String(input.kind).trim(),
    guideCode: code,
    guideFound: code === null || isGuideCode(code),
    startsOn: String(input.startsOn),
    endsOn: (input.endsOn as string | null | undefined) ?? null,
    targetDescription: blankToNull(input.targetDescription),
    sourceUrl: blankToNull(input.sourceUrl),
    active: input.active !== false,
  }
}

const guideNotFound = () =>
  error(404, 'GUIDE_NOT_FOUND', '항목을 찾을 수 없습니다.')
const dateOrder = () => invalid('endsOn 은 startsOn 보다 빠를 수 없습니다.')

/** BE `TaxKind.matches`: same kind, or a linked tax rule of that kind. */
const matches = (schedule: AdminSchedule, kind: string) =>
  schedule.kind === kind ||
  (schedule.guideCode !== null &&
    taxKindByGuideCode[schedule.guideCode] === kind)

const byStart = (a: AdminSchedule, b: AdminSchedule) =>
  a.startsOn.localeCompare(b.startsOn) || a.scheduleId - b.scheduleId

export const adminScheduleHandlers = [
  http.get('*/api/admin/schedules', ({ request }) => {
    const denied = requireAdmin()
    if (denied) return denied
    const year = yearOf(request)
    if (!year) return invalid('year 는 2000~2100 입니다.')
    const kind = (new URL(request.url).searchParams.get('kind') ?? '').trim()
    const rows = data()
      .schedules.filter((schedule) => schedule.startsOn.startsWith(`${year}-`))
      .filter((schedule) => !kind || matches(schedule, kind))
      .sort(byStart)
    return HttpResponse.json({ data: rows })
  }),

  http.post('*/api/admin/schedules', async ({ request }) => {
    const denied = requireAdmin()
    if (denied) return denied
    const input = await body(request)
    if (badInput(input)) return invalid()
    const { guideFound, ...next } = values(input)
    if (!guideFound) return guideNotFound()
    if (next.endsOn && next.endsOn < next.startsOn) return dateOrder()
    const store = data()
    const schedule: AdminSchedule = {
      scheduleId: store.nextId++,
      ...next,
      autoGenerated: false,
      createdBy: currentMember()?.id ?? null,
      updatedBy: null,
      updatedAt: new Date().toISOString(),
    }
    store.schedules.push(schedule)
    persist()
    return HttpResponse.json({ data: schedule }, { status: 201 })
  }),

  http.put('*/api/admin/schedules/:scheduleId', async ({ request, params }) => {
    const denied = requireAdmin()
    if (denied) return denied
    const input = await body(request)
    if (badInput(input)) return invalid()
    const schedule = data().schedules.find(
      (item) => item.scheduleId === Number(params.scheduleId),
    )
    if (!schedule)
      return error(404, 'SCHEDULE_NOT_FOUND', '일정을 찾을 수 없습니다.')
    const { guideFound, ...next } = values(input)
    if (!guideFound) return guideNotFound()
    if (next.endsOn && next.endsOn < next.startsOn) return dateOrder()
    Object.assign(schedule, next, {
      updatedBy: currentMember()?.id ?? null,
      updatedAt: new Date().toISOString(),
    })
    persist()
    return HttpResponse.json({ data: schedule })
  }),

  http.post('*/api/admin/schedules/taxes/generate', ({ request }) => {
    const denied = requireAdmin()
    if (denied) return denied
    const year = yearOf(request)
    if (!year) return invalid('year 는 2000~2100 입니다.')
    const store = data()
    const now = new Date().toISOString()
    // A round exists when the month has the same tax, off or edited too.
    const created = periods
      .filter(
        (period) =>
          !store.schedules.some(
            (schedule) =>
              schedule.startsOn.startsWith(`${year}-${pad(period.month)}-`) &&
              matches(schedule, period.kind),
          ),
      )
      .map((period) => regular(store.nextId++, year, period, now))
    store.schedules.push(...created)
    persist()
    const result: TaxScheduleGenerateResponse = {
      year,
      created,
      // The mock has no holiday data; true when nothing was made, as in the BE.
      officialHolidays: created.length === 0,
    }
    return HttpResponse.json({ data: result })
  }),
]
